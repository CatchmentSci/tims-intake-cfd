"""Table tab:Rall (Appendix A): R of every medium-mesh sweep run, compact (one row per design).

For each design and velocity, over the averaging window (second half of the run):
  R          mean intake ratio
  u_in       bore mean velocity R*U (mm/s)
  s.d.       standard deviation of R over the window, % of the mean (reports every 0.2 s)
  range      max - min of R over the window, % of the mean
  halves     mean of the second half of the window minus the first, % of the mean (drift)
  imbalance  |mean inflow - mean outflow| at the mouth plane over mean inflow
The mesh error of each design at 0.3 m/s (Table tab:verification) goes in the group header.
Run from cfd/: python geometry/table_R.py   (writes ../paper/sections/appendix_R_table.tex)
Velocities still running are skipped, so rerun it as the sweep completes.
"""
import csv
import json
from pathlib import Path

import numpy as np

from tims_geometry import SPECS

SWEEP = [0.154, 0.3, 0.585, 1.0, 1.25, 1.5]
DESIGNS = [  # label, results folder, run, medium-mesh error at 0.3 m/s (tab:verification)
    ("Phillips", "urans_v5", "phillips2000", r"$-3.3$\,\%"),
    ("Perks", "urans_v5", "perks2014", r"$-0.55$\,\%"),
    ("Perks + meter", "urans_v5", "perks2014_flowmeter", r"$-0.36$\,\%"),
    ("Elliott", "urans_v5", "elliott2017", r"$-1.4$\,\%"),
    ("McDonald", "urans_v5bore", "mcdonald2010", r"$-1.6$\,\%"),
    ("Foets", "foets", "foets2020", r"$-2.7$\,\%"),
]
OUT = Path("../paper/supplemental/tab_S7.tex")  # Table S7 of the supplement


def qfmt(q):
    """Intake flow in mL/min: 1 decimal below 10, else 3 significant figures."""
    if q < 10:
        return f"{q:.1f}"
    e = int(np.floor(np.log10(q)))
    return f"{round(q, 2 - e):.{max(0, 2 - e)}f}"


def metrics(base, U):
    """Window statistics of one run, or None if it has not finished."""
    summary = base / f"U{U:.3f}_summary.json"
    if not summary.exists():
        return None
    s = json.load(open(summary))
    rows = list(csv.DictReader(open(base / f"U{U:.3f}_timeseries.csv")))
    t = np.array([float(r["t"]) for r in rows])
    w = (t >= s["average_from"] - 1e-6) & (t <= s["sim_time"] + 1e-6)
    R = np.array([float(r["R"]) for r in rows])[w]
    up = np.array([float(r["mdot_mouth_up"]) for r in rows])[w]
    down = np.array([float(r["mdot_mouth_down"]) for r in rows])[w]
    mean = s["mean"]["R"]
    half = len(R) // 2
    return dict(U=U, dt=s["dt"], T=s["sim_time"], R=mean, uin=1e3 * mean * U,
                sd=100 * R.std() / mean, rng=100 * (R.max() - R.min()) / mean,
                halves=100 * (R[half:].mean() - R[:half].mean()) / mean,
                imb=abs(up.mean() + down.mean()) / abs(up.mean()), n=len(R))


def sci(x):
    """1.2e-05 -> $1\\times10^{-5}$ (one significant figure)."""
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(x)))
    m = round(x / 10 ** e)
    if m == 10:
        m, e = 1, e + 1
    return rf"${m}\times10^{{{e}}}$"


def pct(x):
    """Percentages to two decimals, floored at 0.01 %."""
    if abs(x) < 0.005:
        return r"$<$0.01"
    return f"{x:.2f}".replace("-", "$-$")


def main():
    """Compact layout (the 36-row version overflowed the page): one row per design, R at the
    six velocities, the mesh error, and the largest s.d. and drift of the design's runs; time step and
    run length once, in the header. Per-run statistics are in the supplement's run list."""
    cols = len(SWEEP)
    hdr_u = " & ".join(f"{U:g}" for U in SWEEP)
    lines = [
        r"% Generated by cfd/geometry/table_R.py -- do not edit by hand; rerun the script.",
        r"\begin{table}[!htb]",
        r"\centering",
        r"\caption{Intake ratio $R$ of every design at every velocity (medium meshes; per-run values in",
        r"Table~\ref{tab:S5}). The mesh error is that of the",
        r"medium mesh at \SI{0.3}{m.s^{-1}} (Table~2 of the paper).\label{tab:S7}}",
        r"\footnotesize",
        rf"\begin{{tabular*}}{{\textwidth}}{{@{{\extracolsep\fill}}l{'c' * cols}ccc@{{\extracolsep\fill}}}}",
        r"\toprule",
        rf" & \multicolumn{{{cols}}}{{c}}{{$U$ (\si{{m.s^{{-1}}}})}} & Mesh & Max s.d. & Max drift \\",
        rf"\cmidrule(lr){{2-{cols + 1}}}",
        rf"Design & {hdr_u} & error (\%) & (\%)$^{{\rm a}}$ & (\%)$^{{\rm b}}$ \\",
    ]
    dt_row, T_row, body, imb_max, missing, low = None, None, [], 0.0, [], 0.0
    qrows, bores = [], []
    for label, folder, run, mesh in DESIGNS:
        base = Path("results") / folder / f"{run}_s1.00_sst-gamma"
        ms = []
        for U in SWEEP:
            m = metrics(base, U)
            if m is None:
                missing.append(f"{label} {U:g}")
            ms.append(m)
        done = [m for m in ms if m]
        if dt_row is None and len(done) == cols:
            dt_row = " & ".join(f"{m['dt']:g}" for m in ms)
            T_row = " & ".join(f"{m['T']:g}" for m in ms)
        sd = max(done, key=lambda m: m["sd"])
        dr = max(done, key=lambda m: abs(m["halves"]))
        imb_max = max([imb_max] + [m["imb"] for m in done])
        low = max([low] + [max(m["sd"], abs(m["halves"])) for m in done if m["U"] <= 0.6])
        at = lambda m: rf"\,({m['U']:g})" if abs(m["sd"] if m is sd else m["halves"]) >= 0.005 else ""
        mesh_pct = mesh.replace(r"\,\%", "")
        body.append(f"{label} & " + " & ".join(f"{m['R']:.3f}" if m else "--" for m in ms) +
                    f" & {mesh_pct} & {pct(sd['sd'])}{at(sd)} & {pct(abs(dr['halves']))}{at(dr)}" + r" \\")
        d = SPECS[run].tube_id
        bores.append(f"{label} {1e3 * d:g}")
        qrows.append(f"{label} & " + " & ".join(qfmt(m["R"] * m["U"] * np.pi * d**2 / 4 * 6e7) if m else "--"
                                                for m in ms) + r" & & & \\")
        print(f"{label}: max sd {sd['sd']:.3f}% at {sd['U']}, max |drift| {abs(dr['halves']):.3f}% at {dr['U']}")
    lines += [rf"\quad $\Delta t$ (s) & {dt_row} & & & \\", rf"\quad Run length (s) & {T_row} & & & \\",
              r"\midrule"] + body
    lines += [r"\midrule", rf" & \multicolumn{{{cols}}}{{c}}{{\textit{{Intake flow $q = R\,U\,A_\mathrm{{in}}$ (\si{{mL.min^{{-1}}}})}}}} & & & \\"] + qrows
    lines += [r"\bottomrule", r"\end{tabular*}", r"\begin{tablenotes}",
              r"\item[$^{\rm a}$] Largest s.d.\ of $R$ over the averaging window among the six runs, as a",
              r"percentage of the mean, with its velocity (\si{m.s^{-1}}).",
              r"\item[$^{\rm b}$] Largest $|$mean of the second half of the window minus that of the",
              r"first$|$, as a percentage of the mean.",
              r"\item Inlet-bore diameter for $A_\mathrm{in}$ (mm): " + ", ".join(bores) + ".",
              (r"\item Not yet run or still running: " + ", ".join(missing) + r" \si{m.s^{-1}}.") if missing else "",
              r"\end{tablenotes}", r"\end{table}"]
    OUT.write_text("\n".join(l for l in lines if l) + "\n", encoding="utf-8")
    print("missing:", ", ".join(missing) or "none", "| max imbalance", f"{imb_max:.1e}")


if __name__ == "__main__":
    main()
